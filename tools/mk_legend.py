# Builds src/replay_legend.h: the replay key legend (F1..F9) pre-rendered at 3x as two
# coverage masks (box, text) plus the x range of each item, so the DLL needs no font.
import sys
from PIL import Image, ImageDraw, ImageFont
S = 3
K = 1.45   # size of the legend relative to the first version
S3 = S
S = S * K
FONT = '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf'
f = ImageFont.truetype(FONT, int(9 * S))
items = [('⇧F1', 'start', ''), ('F1', 'lapb', 'lap'), ('F2', 'lapf', 'lap'), ('⇧F2', 'end', ''), ('F3', 'playpause', ''), ('F4', 'play', 'slow'), ('F5', 'rew', ''),
         ('F6', 'stepb', ''), ('F7', 'stepf', ''), ('F8', 'ff', ''), ('F9', '', 'hide')]
H = int(15 * S); pad = 4 * S; gap = 4.5 * S; icon_w = {'': 0, 'lapb': 16, 'lapf': 16, 'playpause': 14, 'rew': 11, 'stepb': 9, 'start': 11, 'pause': 7, 'play': 6, 'stepf': 9, 'ff': 11, 'end': 11}
def icon(d, kind, x, cy, col):
    h = 3.4 * S
    def tri(x0, right):   # triangle 5 px wide
        w = 5 * S
        if right: d.polygon([(x0, cy - h), (x0 + w, cy), (x0, cy + h)], fill=col)
        else: d.polygon([(x0 + w, cy - h), (x0, cy), (x0 + w, cy + h)], fill=col)
        return x0 + w
    def bar(x0): d.rectangle([x0, cy - h, x0 + 1.6 * S, cy + h], fill=col); return x0 + 1.6 * S
    if kind == 'lapb': tri(x, 0); tri(x + 5.5 * S, 0); tri(x + 11 * S, 0)
    elif kind == 'lapf': tri(x, 1); tri(x + 5.5 * S, 1); tri(x + 11 * S, 1)
    elif kind == 'playpause': tri(x, 1); bar(x + 7 * S); bar(x + 10.5 * S)
    elif kind == 'rew': tri(x, 0); tri(x + 5.5 * S, 0)
    elif kind == 'stepb': b = bar(x); tri(b + 1.2 * S, 0)
    elif kind == 'start': b = bar(x); tri(b + 0.6 * S, 0); tri(b + 5 * S, 0)
    elif kind == 'pause': bar(x + 0.5 * S); bar(x + 4.3 * S)
    elif kind == 'play': tri(x, 1)
    elif kind == 'stepf': e = tri(x, 1); bar(e + 1.2 * S)
    elif kind == 'ff': tri(x, 1); tri(x + 5.5 * S, 1)
    elif kind == 'end': e = tri(x, 1); e = tri(e - 0.6 * S, 1); bar(e + 0.6 * S)
# measure
def tw(t): return f.getlength(t)
xs = []; x = pad
for k, ic, word in items:
    w = tw(k) + 3 * S + icon_w[ic] * S + ((3 * S if ic else 0) + tw(word) if word else 0)
    xs.append((int(x - gap / 2 + 1), int(x + w + gap / 2 - 1))); x += w + gap
W = int(x - gap + pad); W += (-W) % 4
box = Image.new('L', (W, H), 0); ImageDraw.Draw(box).rounded_rectangle([0, 0, W - 1, H - 1], radius=int(4 * S), fill=255)
txt = Image.new('L', (W, H), 0); d = ImageDraw.Draw(txt)
x = pad; cy = H / 2
for (k, ic, word), (a, b) in zip(items, xs):
    d.text((x, cy), k, font=f, fill=150, anchor='lm'); x += tw(k) + 3 * S
    if ic: icon(d, ic, x, cy, 255)
    x += icon_w[ic] * S
    if word: x += (3 * S if ic else 0); d.text((x, cy), word, font=f, fill=255, anchor='lm'); x += tw(word)
    x += gap
bb = box.tobytes(); tb = txt.tobytes()
o = open(sys.argv[1], 'w')
o.write('/* generated by tools/mk_legend.py (DejaVu Sans Condensed Bold) - do not edit */\n')
o.write('#define RL_SCALE %d\n#define RL_W %d\n#define RL_H %d\n#define RL_N %d\n' % (S3, W, H, len(items)))
o.write('static const short rl_item[RL_N][2] = {%s};\n' % ','.join('{%d,%d}' % p for p in xs))
def arr(name, b):
    o.write('static const unsigned char %s[RL_W * RL_H] = {' % name)
    o.write(','.join(str(v) for v in b)); o.write('};\n')
arr('rl_box', bb); arr('rl_txt', tb)
prev = Image.merge('RGB', (txt, txt, box)); prev.save(sys.argv[2])
print(W, H, xs)
