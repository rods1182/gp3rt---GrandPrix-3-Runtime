# Generates src/gp3replay_tab.h: Rafa's Gp3Video as an in-memory patch with relocation.
# usage: gen_mem.py Gp3Video.exe gp3.exe(1.13) gp3v.exe out.h
import struct, sys, subprocess, re
tool, src, gv, out = sys.argv[1:5]
d = open(tool, 'rb').read(); ds = d[1024 + 0x3810:]
def table(o):
    r = []
    while True:
        a, v = struct.unpack_from('<II', ds, o)
        if a == 0xffffffff: return r
        r.append((a, v)); o += 8
g = open(src, 'rb').read(); n = open(gv, 'rb').read()
IMG = 0x400000; CODE = 0xd25000; DATA = 0xd26000; DEND = 0x1a16000
chk = table(0x42); pat = [(a, v) for a, v in table(0x6a) if a >= 0x1000]
page = bytearray(n[0x86d000:0x86e000])
# game-code relocations, found in the finished gp3v.exe
dabs, crel = [], []
sites = set()
for a, v in pat:
    for k in range(4): sites.add(a + k)
for o in sorted(sites):
    if o + 4 > len(g): continue
    v = struct.unpack_from('<I', n, o)[0]
    if n[o - 1] in (0xe8, 0xe9) and (o - 1) in sites | {o - 1}:
        t = (IMG + o + 4 + v) & 0xffffffff
        if CODE <= t < DATA and (o, 'r') not in crel: crel.append(o); continue
for a, v in pat:
    if DATA <= v < DEND and v != 0xd4a890: dabs.append(a)     # 0xd4a890 is a byte count (replay file size), not an address
crel = sorted(set(crel))
# blob relocations from an aligned disassembly
dis = subprocess.run(['objdump', '-d', '-M', 'intel', '--start-address=0xd25100', '--stop-address=0xd2532d', gv], capture_output=True, text=True).stdout
bout, bdat = [], []
for line in dis.splitlines():
    m = re.match(r'\s+([0-9a-f]+):\s+((?:[0-9a-f]{2} )+)\s*(.*)', line)
    if not m: continue
    va = int(m.group(1), 16); by = bytes.fromhex(m.group(2).replace(' ', ''))
    if by[0] in (0xe8, 0xe9) and len(by) == 5:
        t = (va + 5 + struct.unpack_from('<i', by, 1)[0]) & 0xffffffff
        if not (CODE <= t < DATA): bout.append(va + 1 - CODE)
    for k in range(len(by) - 3):
        v = struct.unpack_from('<I', by, k)[0]
        if DATA <= v < DEND: bdat.append(va + k - CODE)
print('patches', len(pat), 'data abs', len(dabs), 'code rel', [hex(IMG + x) for x in crel], 'blob out', len(bout), 'blob data', [hex(x) for x in bdat])
f = open(out, 'w')
f.write('/* generated by tools_gp3video/gen_mem.py from Rafa\'s Gp3Video (in-memory form for GP3Replay.dll) - do not edit */\n')
f.write('static const uint32_t gv_check[][2] = {%s};\n' % ','.join('{0x%x,0x%x}' % (IMG + a, v) for a, v in chk))
f.write('static const uint32_t gv_patch[][3] = {\n%s};\n' % ',\n'.join('{0x%x,0x%x,0x%x}' % (IMG + a, struct.unpack_from('<I', g, a)[0], v) for a, v in pat))
f.write('static const uint32_t gv_data_abs[] = {%s};\n' % ','.join('0x%x' % (IMG + a) for a in dabs))
f.write('static const uint32_t gv_code_rel[] = {%s};\n' % ','.join('0x%x' % (IMG + a) for a in crel))
f.write('static const uint16_t gv_blob_out[] = {%s};\n' % ','.join('0x%x' % x for x in bout))
f.write('static const uint16_t gv_blob_data[] = {%s};\n' % ','.join('0x%x' % x for x in bdat))
f.write('static const uint8_t gv_page[0x400] = {%s};\n' % ','.join(str(b) for b in page[:0x400]))
f.write('#define GV_CODE 0x%xu\n#define GV_DATA 0x%xu\n#define GV_DATA_SIZE 0x%xu\n' % (CODE, DATA, DEND - DATA))
